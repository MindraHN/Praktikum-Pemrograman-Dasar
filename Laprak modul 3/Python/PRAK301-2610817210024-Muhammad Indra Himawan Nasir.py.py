print("=== Pengurutan Angka ===")

a = int(input("Masukkan angka pertama: "))
b = int(input("Masukkan angka kedua: "))
c = int(input("Masukkan angka ketiga: "))

if a > b:
    a, b = b, a
if a > c:
    a, c = c, a
if b > c:
    b, c = c, b

print(f"Hasil pengurutan (terkecil ke terbesar): {a}, {b}, {c}")